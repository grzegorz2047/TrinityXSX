"""Write the capture page as C for prospero-win's runner (src/pw_webinput_page.c).

The page lives once, in tools/netinput-sender/src/web/index.html: txin-sender serves it on 127.0.0.1 and the
PS5 runner (patches/prospero-win/0013) serves it on the LAN. Run this after changing the page and refresh the
patch:

    python tools/netinput-sender/make_page_c.py <prospero-win checkout>/src/pw_webinput_page.c
    python tools/netinput-sender/make_page_c.py --check <prospero-win checkout>/src/pw_webinput_page.c
"""

import sys
from pathlib import Path

PAGE = Path(__file__).resolve().parent / "src" / "web" / "index.html"


def render(page: bytes) -> str:
    lines = [
        "/* SPDX-License-Identifier: LGPL-2.1-or-later */",
        "/* Generated by TrinityXSX's tools/netinput-sender/make_page_c.py from its src/web/index.html;",
        " * do not edit: change the page there and run the script again. */",
        '#include "pw_webinput.h"',
        "",
        "const char pw_webinput_page[] =",
    ]
    for chunk in page.splitlines(keepends=True):
        # Octal escapes for anything outside printable ASCII (UTF-8 bytes too), quotes, backslashes and '?'
        # (no trigraphs); always three digits, so a following digit is never read as part of the escape.
        text = "".join(chr(b) if 0x20 <= b < 0x7F and chr(b) not in '"\\?' else "\\%03o" % b for b in chunk)
        lines.append(f'    "{text}"')
    lines[-1] += ";"
    lines.append(f"const size_t pw_webinput_page_length = {len(page)};")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    check = argv[:1] == ["--check"]
    paths = argv[1:] if check else argv
    if len(paths) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    target = Path(paths[0])
    page = PAGE.read_bytes().replace(b"\r\n", b"\n")
    text = render(page)
    if check:
        if not target.exists() or target.read_text(encoding="ascii").replace("\r\n", "\n") != text:
            print(f"{target} is not the page in {PAGE}: run make_page_c.py again", file=sys.stderr)
            return 1
        return 0
    target.write_text(text, encoding="ascii", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
