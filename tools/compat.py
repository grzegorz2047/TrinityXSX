"""TrinityXSX game compatibility database (library/compat.toml).

  python tools/compat.py --check              validate the database and that docs/COMPATIBILITY.md is current
  python tools/compat.py --write              regenerate the table in docs/COMPATIBILITY.md
  python tools/compat.py --from-issue         add or update the entry of a "Game compatibility report"
                                              (issue form body in $ISSUE_BODY, number in $ISSUE_NUMBER)

The issue body is untrusted text: it is only parsed, never executed, and only an allowlist of
xcl.toml keys with the right types is taken from it.
"""
from __future__ import annotations

import argparse
import os
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DB = ROOT / "library" / "compat.toml"
DOC = ROOT / "docs" / "COMPATIBILITY.md"
BEGIN = "<!-- compat:begin (generated by tools/compat.py from library/compat.toml; do not edit) -->"
END = "<!-- compat:end -->"

STATUSES = {
    "playable": "Playable",
    "ingame": "In-game (issues)",
    "menus": "Menus",
    "boots": "Boots / loading",
    "nothing": "Does not start",
}
# the issue form's "Current state" options
FORM_STATUS = {
    "Does not appear in the library": "nothing",
    "Crashes on launch / returns to PS5 home screen": "nothing",
    "Black screen or freezes during loading": "boots",
    "Menus work, crashes or hangs entering gameplay": "menus",
    "In-game with graphics / audio / controller issues": "ingame",
    "Playable": "playable",
}
KEYS_FILE = ROOT / "library" / "compat_keys.txt"


RANGES = {"u32": (0, 2**32 - 1), "u64": (0, 2**64 - 1)}


def read_keys(path: Path = KEYS_FILE) -> dict[str, tuple[str, object]]:
    """xcl.toml keys an entry may set: name -> (type, PS5 default) (library/compat_keys.txt)."""
    keys = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        name, kind, default = line.split(None, 2)
        keys[name] = (kind, tomllib.loads(f"v = {default}")["v"])
    return keys


# xcl.toml keys an entry may set, with their types and PS5 defaults; anything else is ignored
XCL_KEYS: dict[str, tuple[str, object]] = read_keys()


def valid_xcl_value(key: str, value) -> bool:
    kind = XCL_KEYS[key][0]
    if kind == "str":
        # shown in a code span in the table: plain setting values only ("12_0", "lockhart", "")
        return type(value) is str and re.fullmatch(r"[A-Za-z0-9._,:+\- ]{0,64}", value) is not None
    if kind == "bool":
        return type(value) is bool
    low, high = RANGES[kind]
    return type(value) is int and low <= value <= high


# characters that would make Markdown, HTML or the generated table do something in docs/COMPATIBILITY.md
UNSAFE_TEXT = set("<>`[]*_|\\\n\r")
FIELDS = ("title_id", "identity", "name", "versions", "status", "release", "notes", "reports")
MAX_TEXT = 200


class CompatError(ValueError):
    pass


def load(path: Path = DB) -> list[dict]:
    data = tomllib.loads(path.read_text(encoding="utf-8"))
    titles = data.get("title", [])
    validate(titles)
    return titles


def validate(titles: list[dict]) -> None:
    seen = set()
    for i, t in enumerate(titles):
        where = f"title #{i + 1} ({t.get('name', '?')})"
        missing = [f for f in FIELDS if f not in t]
        if missing:
            raise CompatError(f"{where}: missing {', '.join(missing)}")
        unknown = set(t) - set(FIELDS) - {"xcl"}
        if unknown:
            raise CompatError(f"{where}: unknown field(s) {', '.join(sorted(unknown))}")
        if t["title_id"] and not re.fullmatch(r"[0-9A-F]{8}", t["title_id"]):
            raise CompatError(f"{where}: title_id must be 8 upper-case hex digits or empty")
        if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9.\-]{1,99}", t["identity"]):
            raise CompatError(f"{where}: invalid identity {t['identity']!r}")
        if t["status"] not in STATUSES:
            raise CompatError(f"{where}: status must be one of {', '.join(STATUSES)}")
        for key in ("name", "release", "notes"):
            if not isinstance(t[key], str) or len(t[key]) > MAX_TEXT or set(t[key]) & UNSAFE_TEXT:
                raise CompatError(f"{where}: {key} must be one line of at most {MAX_TEXT} characters, without < > ` [ ] * _ | \\")
        if not all(isinstance(v, str) and re.fullmatch(r"\d+(\.\d+){1,3}", v) for v in t["versions"]):
            raise CompatError(f"{where}: versions must be like 1.2.3.0")
        if not all(isinstance(n, int) and n > 0 for n in t["reports"]):
            raise CompatError(f"{where}: reports must be issue numbers")
        for key, value in t.get("xcl", {}).items():
            if key not in XCL_KEYS:
                raise CompatError(f"{where}: xcl.{key} is not an allowed xcl.toml key")
            if not valid_xcl_value(key, value):
                raise CompatError(f"{where}: xcl.{key} must be a {XCL_KEYS[key][0]} (in range, plain text)")
        key = (t["title_id"] or t["identity"]).casefold()
        if key in seen:
            raise CompatError(f"{where}: duplicate entry")
        seen.add(key)


def table(titles: list[dict]) -> str:
    rows = ["| Title | Identity, version & TitleId | Status | TrinityXSX | Notes |", "| --- | --- | --- | --- | --- |"]
    order = list(STATUSES)
    for t in sorted(titles, key=lambda t: (order.index(t["status"]), t["name"].casefold())):
        ident = f"`{t['identity']}`"
        if t["versions"]:
            ident += " " + ", ".join(f"`{v}`" for v in t["versions"])
        if t["title_id"]:
            ident += f" (`{t['title_id']}`)"
        notes = t["notes"]
        if t.get("xcl"):
            notes += " Preset: " + ", ".join(f"`{k} = {fmt(v)}`" for k, v in t["xcl"].items()) + "."
        if t["reports"]:
            notes += " Reports: " + ", ".join(f"#{n}" for n in t["reports"]) + "."
        rows.append(f"| **{t['name']}** | {ident} | **{STATUSES[t['status']]}** | {t['release']} | {notes} |")
    return "\n".join(rows)


def fmt(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, str):
        return f'"{v}"'
    return str(v)


def render_doc(doc: str, titles: list[dict]) -> str:
    if BEGIN not in doc or END not in doc:
        raise CompatError(f"{DOC.name} has no {BEGIN!r} ... {END!r} section")
    head, rest = doc.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{BEGIN}\n{table(titles)}\n{END}{tail}"


# ---- issue form -> entry -------------------------------------------------------------------

# the labels of .github/ISSUE_TEMPLATE/game_compatibility.yml (and the old combined game field)
FORM_LABELS = (
    "TrinityXSX release version",
    "Installation mode",
    "PS5 firmware & homebrew setup",
    "Game name",
    "Identity Name",
    "Package version",
    "TitleId",
    "Game name, Identity Name, Version, and TitleId",
    "Current state",
    "Game folder path on PS5",
    "xcl.toml settings used",
    "Steps to reproduce & observed behavior",
    "Logs, screenshots or video",
)


def form_sections(body: str) -> dict[str, str]:
    """The form's `### Label` sections. Only the form's own labels count, and only their first
    occurrence: a `### Identity Name` typed into a later free-text field must not replace the
    real field. Any other `### ...` line is text of the section it is in."""
    sections: dict[str, str] = {}
    label = None
    for line in body.replace("\r\n", "\n").split("\n"):
        m = re.match(r"^###\s+(.+?)\s*$", line)
        if m and m.group(1) in FORM_LABELS and m.group(1) not in sections:
            label = m.group(1)
            sections[label] = ""
        elif label is not None:
            sections[label] += line + "\n"
    return {k: v.strip() for k, v in sections.items() if v.strip() and v.strip() != "_No response_"}


def one_line(text: str, field: str) -> str:
    """Report text as one plain line: the characters Markdown or HTML would act on become spaces."""
    text = "".join(" " if c in UNSAFE_TEXT else c for c in text)
    text = " ".join(text.split())
    if not text:
        raise CompatError(f"{field} is empty")
    return text[:MAX_TEXT]


def entry_from_issue(body: str, number: int) -> dict:
    s = form_sections(body)
    title_id = s.get("TitleId", "")
    identity = s.get("Identity Name", "")
    version = s.get("Package version", "")
    name = s.get("Game name", "")
    legacy = s.get("Game name, Identity Name, Version, and TitleId", "")
    if legacy and not identity:
        # "Example Game — Publisher.ExampleGame 1.2.3.0 (TitleId 1234ABCD)"
        m = re.search(r"TitleId\s*[:#]?\s*([0-9A-Fa-f]{8})", legacy)
        title_id = m.group(1) if m else ""
        m = re.search(r"\b(\d+\.\d+\.\d+\.\d+)\b", legacy)
        version = m.group(1) if m else ""
        m = re.search(r"\b([A-Za-z0-9][A-Za-z0-9\-]*(?:\.[A-Za-z0-9\-]+)+)\b", legacy.replace(version, " "))
        identity = m.group(1) if m else ""
        name = re.split(r"\s+[—–-]\s+|\s+\(", legacy, maxsplit=1)[0]
    title_id = title_id.strip().upper()
    if title_id and not re.fullmatch(r"[0-9A-F]{8}", title_id):
        raise CompatError(f"TitleId {title_id!r} is not 8 hex digits")
    identity = identity.strip()
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9.\-]{1,99}", identity):
        raise CompatError(f"Identity Name {identity!r} is not valid")
    version = version.strip()
    if version and not re.fullmatch(r"\d+(\.\d+){1,3}", version):
        raise CompatError(f"version {version!r} is not like 1.2.3.0")
    state = s.get("Current state", "")
    if state not in FORM_STATUS:
        raise CompatError(f"unknown state {state!r}")
    release = re.match(r"v?\d+\.\d+\.\d+", s.get("TrinityXSX release version", "").strip())
    if not release:
        raise CompatError("TrinityXSX release version is not like v0.2.7")
    notes = one_line(s.get("Steps to reproduce & observed behavior", "Reported working."), "notes")
    return {
        "title_id": title_id,
        "identity": identity,
        "name": one_line(name or identity, "name"),
        "versions": [version] if version else [],
        "status": FORM_STATUS[state],
        "release": release.group(0) if release.group(0).startswith("v") else "v" + release.group(0),
        "notes": notes,
        "reports": [number],
        # a PC test's settings are not a PS5 preset
        "xcl": {} if "PC test" in s.get("Installation mode", "") else xcl_from_text(s.get("xcl.toml settings used", "")),
    }


def xcl_from_text(text: str) -> dict:
    """What an xcl.toml pasted into the form changes from the PS5 defaults: allowed keys with valid
    values that differ from the default. A whole pasted file thus gives only what was tuned."""
    text = re.sub(r"^```\w*\s*$", "", text, flags=re.M)
    try:
        data = tomllib.loads(text)
    except tomllib.TOMLDecodeError:
        return {}
    return {
        k: v for k, v in data.items() if k in XCL_KEYS and valid_xcl_value(k, v) and v != XCL_KEYS[k][1]
    }


def upsert(titles: list[dict], new: dict) -> list[dict]:
    key = (new["title_id"] or new["identity"]).casefold()
    for t in titles:
        if (t["title_id"] or t["identity"]).casefold() == key or t["identity"].casefold() == new["identity"].casefold():
            t["name"] = t["name"] or new["name"]
            for v in new["versions"]:
                if v not in t["versions"]:
                    t["versions"].append(v)
            t["status"], t["release"], t["notes"] = new["status"], new["release"], new["notes"]
            t["reports"] = sorted(set(t["reports"]) | set(new["reports"]))
            if new["xcl"]:
                # a report adds to the preset; it does not drop what earlier reports needed
                t["xcl"] = {**t.get("xcl", {}), **new["xcl"]}
            return titles
    if not new["xcl"]:
        new.pop("xcl")
    return titles + [new]


def dump(titles: list[dict]) -> str:
    """compat.toml text: the header comment of the current file, then the entries."""
    header = []
    for line in DB.read_text(encoding="utf-8").splitlines():
        if line.startswith("[[title]]"):
            break
        header.append(line)
    out = "\n".join(header).rstrip("\n") + "\n"
    for t in titles:
        out += "\n[[title]]\n"
        for f in FIELDS:
            out += f"{f} = {toml_value(t[f])}\n"
        if t.get("xcl"):
            out += "\n[title.xcl]\n" + "".join(f"{k} = {toml_value(v)}\n" for k, v in t["xcl"].items())
    return out


def toml_value(v) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, list):
        return "[" + ", ".join(toml_value(x) for x in v) + "]"
    s = str(v).replace("\\", "\\\\").replace('"', '\\"')
    return f'"{s}"'


def describe(entry: dict) -> str:
    """One line naming the game an entry is for, for the PR title."""
    tid = f" ({entry['title_id']})" if entry["title_id"] else ""
    return f"{entry['identity']}{tid}: {entry['status']}"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--from-issue", action="store_true")
    args = ap.parse_args()
    try:
        titles = load()
        if args.from_issue:
            number = int(os.environ["ISSUE_NUMBER"])
            entry = entry_from_issue(os.environ["ISSUE_BODY"], number)
            print(f"target: {describe(entry)}")
            if os.environ.get("GITHUB_OUTPUT"):
                with open(os.environ["GITHUB_OUTPUT"], "a", encoding="utf-8") as out:
                    out.write(f"target={describe(entry)}\n")
            titles = upsert(titles, entry)
            validate(titles)
            DB.write_text(dump(titles), encoding="utf-8", newline="\n")
            titles = load()
        doc = DOC.read_text(encoding="utf-8")
        rendered = render_doc(doc, titles)
        if args.check:
            if rendered != doc:
                print("docs/COMPATIBILITY.md is out of date: run python tools/compat.py --write", file=sys.stderr)
                return 1
            print(f"compat OK: {len(titles)} titles")
        else:
            DOC.write_text(rendered, encoding="utf-8", newline="\n")
            print(f"wrote {DOC.relative_to(ROOT)} ({len(titles)} titles)")
    except CompatError as e:
        print(f"compat: {e}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
